import streamlit as st
import requests

from data import get_dodgers_schedule
from prediction_v2 import (
    build_model_data,
    train_v2_model,
    get_next_dodgers_game,
    predict_dodgers_game_v2
)


@st.cache_resource
def load_prediction_model():

    model_data, team_games = build_model_data()

    model = train_v2_model(
        model_data
    )

    return model, team_games


st.title("Dodgers Game Prediction")

try:
    schedule = get_dodgers_schedule()

except requests.exceptions.RequestException:
    st.error(
        "Unable to retrieve MLB data right now. "
        "Please try again later."
    )
    st.stop()


try:
    model, team_games = load_prediction_model()

    next_game = get_next_dodgers_game(
        schedule
    )

    if next_game is not None:
        next_game_prediction = predict_dodgers_game_v2(
            next_game,
            model,
            team_games
        )
    else:
        next_game_prediction = None

except requests.exceptions.RequestException:
    next_game_prediction = None


if next_game_prediction is not None:

    game_type_labels = {
        "R": "Regular Season",
        "F": "Wild Card",
        "D": "Division Series",
        "L": "League Championship Series",
        "W": "World Series"
    }

    game_type = game_type_labels.get(
        next_game_prediction["Game_Type"],
        next_game_prediction["Game_Type"]
    )

    opponent = next_game_prediction["Opponent"]
    home_away = next_game_prediction["Home_Away"]
    game_date = next_game_prediction["Date"]

    win_probability = (
        next_game_prediction["Dodgers_Win_Probability"]
    )

    loss_probability = 1 - win_probability

    st.subheader(
        f"Dodgers vs. {opponent}"
        if home_away == "Home"
        else f"Dodgers at {opponent}"
    )

    st.write(
        f"{game_type} — "
        f"{game_date.strftime('%B %d, %Y')}"
    )

    col1, col2 = st.columns(2)

    with col1:
        st.metric(
            "Dodgers Win Probability",
            f"{win_probability:.1%}"
        )

    with col2:
        st.metric(
            "Dodgers Loss Probability",
            f"{loss_probability:.1%}"
        )

    st.progress(
        float(win_probability)
    )

    with st.expander("How is this prediction calculated?"):
        st.write(
            "This prediction is generated by a Random Forest machine "
            "learning model trained on completed MLB regular-season games "
            "from 2023 through 2026."
        )

        st.write(
            "The model compares the Dodgers and their opponent using both "
            "recent 10-game performance and season-to-date performance."
        )

        st.markdown(
            """
            **Model features:**
            - Recent 10-game win percentage
            - Recent 10-game average runs scored
            - Recent 10-game average runs allowed
            - Season-to-date win percentage
            - Season-to-date run differential per game
            - The same five statistics for the opponent
            """
        )

        st.caption(
            "Predictions are statistical estimates based on historical "
            "performance and do not guarantee game outcomes."
        )

else:
    st.info(
        "A prediction is not currently available "
        "for the next Dodgers game."
    )